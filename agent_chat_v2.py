# agent_chat_v2.py
# บอท 1: แผนกพูดคุยและวิเคราะห์คำสั่ง (Chat Agent)

class ChatAgent:
    def __init__(self):
        self.name = "บอทพูดคุย (บอท 1)"

    def response(self, user_message, session_id, db_agent):
        """
        วิเคราะห์ข้อความที่ผู้ใช้ส่งมา หากพบคำสั่งที่ต้องการทำธุรกรรมเกี่ยวกับฐานข้อมูล 
        จะทำการส่งไม้ต่อให้ บอท 2 (บอทฐานข้อมูล) ทำงานทันที
        """
        msg = user_message.strip()

        # 1. ส่งต่อให้ บอท 2 ทำงานเมื่อพบคำสั่ง "บันทึก" หรือ "จด"
        if msg.startswith("บันทึก ") or msg.startswith("จด "):
            content = msg.replace("บันทึก ", "", 1).replace("จด ", "", 1)
            return db_agent.save_note(session_id, content)

        # 2. ส่งต่อให้ บอท 2 ทำงานเมื่อต้องการเปิดดูข้อมูลเก่า
        elif msg in ["ดูบันทึก", "อ่านบันทึก", "ประวัติ", "แสดงบันทึก"]:
            return db_agent.get_notes(session_id)

        # 3. จัดการตอบคำถามทักทายทั่วไป (ในฐานะบอท 1 เอง)
        if "สวัสดี" in msg or "hello" in msg.lower():
            return (f"สวัสดีครับ! ผมคือ {self.name} ยินดีต้อนรับสู่ระบบจำลองเอเจนต์ของเราครับ! "
                    f"ตอนนี้เรามีเพื่อนร่วมงานอีกตัวคือ 'บอท 2 (บอทฐานข้อมูล)' ครับ "
                    f"คุณสามารถพิมพ์สั่งเราง่ายๆ ได้ดังนี้ครับ:\n\n"
                    f"👉 พิมพ์: 'บันทึก [ข้อความ]' (เช่น 'บันทึก ซื้อนมกล่อง')\n"
                    f"👉 พิมพ์: 'ดูบันทึก' เพื่อเรียกดูข้อมูลทั้งหมด")

        # 4. กรณีพิมพ์เรื่องอื่นๆ ที่ไม่ใช่คำสั่ง
        return (f"ผมคือ {self.name} ยินดีให้บริการครับ!\n"
                f"ผมยังไม่ค่อยเข้าใจประโยคนี้ แต่คุณสามารถสั่งการผมและบอท 2 ได้ด้วยคำสั่งด้านล่างนี้ครับ:\n\n"
                f"🔹 พิมพ์ 'บันทึก [เรื่องที่อยากจด]' -> บอท 2 จะนำไปเก็บใน Firebase\n"
                f"🔹 พิมพ์ 'ดูบันทึก' -> บอท 2 จะไปเปิดสมุดดึงข้อความมาโชว์ครับ")
